const recolour = (shape: string[], [d, m, l, a]: string) =>
  shape.map((row) => row.replace(/[01234]/g, (c) => (c === "0" ? "k" : c === "1" ? d : c === "2" ? m : c === "3" ? l : a)));

// [helmet shape, legs shape, palette: dark main light accent]
